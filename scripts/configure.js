// scripts/configure.js : writes the per-machine configuration (never committed).
//   apps/tp1-ethereum/.env, apps/tp2-fabric/.env, monitor/.env, ledgers/ethereum/ignition/parameters.json
// Keeps TP1's operator key and the JWT secrets if the files already exist, so it can be re-run safely.
// usage: FABRIC_SAMPLES=/path/to/fabric-samples node scripts/configure.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { ethers } = require('ethers');

const ROOT = path.resolve(__dirname, '..');
const SAMPLES = process.env.FABRIC_SAMPLES;
if (!SAMPLES) { console.error('FABRIC_SAMPLES is not set'); process.exit(1); }
const ORGS = path.join(SAMPLES, 'test-network', 'organizations', 'peerOrganizations');
const ADDRESSES = path.join(ROOT, 'ledgers', 'ethereum', 'ignition', 'deployments', 'chain-31337', 'deployed_addresses.json');

function readEnv(file) {
  try {
    return Object.fromEntries(fs.readFileSync(file, 'utf8').split('\n')
      .filter((l) => /^[A-Z_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
  } catch { return {}; }
}
function writeEnv(file, title, sections) {
  const body = sections.map(([comment, vars]) => [`# ${comment}`, ...Object.entries(vars).map(([k, v]) => `${k}=${v}`)].join('\n')).join('\n\n');
  fs.writeFileSync(file, `# ${title}\n# Generated by scripts/configure.js; re-run it instead of editing paths by hand.\n\n${body}\n`);
  console.log(`  wrote ${path.relative(ROOT, file)}`);
}
const secret = () => crypto.randomBytes(32).toString('hex');
const fabricId = (org, port) => ({
  SYNC_FABRIC_CRYPTO_PATH: path.join(ORGS, `${org}.example.com`),
  SYNC_FABRIC_USER: `User1@${org}.example.com`,
  SYNC_FABRIC_MSP: org === 'org1' ? 'Org1MSP' : 'Org2MSP',
  SYNC_FABRIC_PEER: `localhost:${port}`,
  SYNC_FABRIC_PEER_ALIAS: `peer0.${org}.example.com`,
});
const timing = { SYNC_ORIGIN_TTL: 300, SYNC_RESPONDER_TTL: 150, SYNC_MARGIN: 30 };

// ---- TP1 (Ethereum): writes Ethereum with its own key, reads Fabric as User1@org2
const tp1File = path.join(ROOT, 'apps', 'tp1-ethereum', '.env');
const tp1Old = readEnv(tp1File);
const operatorKey = tp1Old.SYNC_ETH_OPERATOR_KEY || ethers.Wallet.createRandom().privateKey;
const operator = new ethers.Wallet(operatorKey).address;
writeEnv(tp1File, 'TP1: medical app on Ethereum (http://localhost:3000)', [
  ['App', { PORT: 3000, JWT_SECRET: tp1Old.JWT_SECRET || secret(), JWT_EXPIRES_IN: '8h' }],
  ['HTLC sync: TP1 writes Ethereum and reads Fabric', { SYNC_APP: 'TP1', SYNC_OWN: 'ethereum', ETH_RPC: 'http://127.0.0.1:8545', ETH_ADDRESSES: ADDRESSES, FABRIC_CHANNEL: 'mychannel' }],
  ['Fabric read identity (Org2)', fabricId('org2', 9051)],
  ['TP1 own Ethereum key: sole operator of HashSyncHTLC. Keep it secret.', { SYNC_ETH_OPERATOR_KEY: operatorKey }],
  ['Deadlines (seconds)', timing],
]);

// ---- TP2 (Fabric): writes Fabric as User1@org1, reads Ethereum
const tp2File = path.join(ROOT, 'apps', 'tp2-fabric', '.env');
const tp2Old = readEnv(tp2File);
writeEnv(tp2File, 'TP2: medical app on Hyperledger Fabric (http://localhost:3001)', [
  ['App', { PORT: 3001, JWT_SECRET: tp2Old.JWT_SECRET || secret(), JWT_EXPIRES_IN: '8h' }],
  ['Fabric identity for the dossier fingerprints (chaincode documents)', {
    FABRIC_CHANNEL: 'mychannel', FABRIC_CHAINCODE: 'documents', FABRIC_MSP_ID: 'Org1MSP', FABRIC_USER: 'User1@org1.example.com',
    FABRIC_PEER_ENDPOINT: 'localhost:7051', FABRIC_PEER_HOST_ALIAS: 'peer0.org1.example.com', FABRIC_CRYPTO_PATH: path.join(ORGS, 'org1.example.com'),
  }],
  ['HTLC sync: TP2 writes Fabric and reads Ethereum', { SYNC_APP: 'TP2', SYNC_OWN: 'fabric', ETH_RPC: 'http://127.0.0.1:8545', ETH_ADDRESSES: ADDRESSES }],
  ['Fabric write identity (Org1)', fabricId('org1', 7051)],
  ['Deadlines (seconds)', timing],
]);

// ---- Monitor: reads both ledgers (Fabric as User1@org2) and both apps
writeEnv(path.join(ROOT, 'monitor', '.env'), 'Read-only sync monitor (http://localhost:3200)', [
  ['Monitor', { MONITOR_PORT: 3200, TP1_URL: 'http://localhost:3000', TP2_URL: 'http://localhost:3001' }],
  ['Ledgers (read only)', { ETH_RPC: 'http://127.0.0.1:8545', ETH_ADDRESSES: ADDRESSES, FABRIC_CHANNEL: 'mychannel' }],
  ['Fabric read identity (Org2)', fabricId('org2', 9051)],
]);

// ---- Ignition parameter: the contract's owner and only operator is TP1's address
const params = path.join(ROOT, 'ledgers', 'ethereum', 'ignition', 'parameters.json');
fs.writeFileSync(params, `${JSON.stringify({ HashSyncHTLCModule: { operator } }, null, 2)}\n`);
console.log(`  wrote ${path.relative(ROOT, params)} (operator ${operator})`);
